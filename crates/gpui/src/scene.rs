/// A [`Mesh`] painted with a transformation and paint (see [`crate::Window::paint_mesh`]).
#[derive(Clone, Debug)]
pub struct MeshDraw {
    /// Composite operation for this mesh.
    pub blend_mode: crate::MeshBlendMode,
    /// The draw order, assigned when the draw is inserted into a scene.
    pub order: DrawOrder,
    /// The area the draw may paint: the transformed mesh bounds, rounded out to whole device
    /// pixels.
    pub bounds: Bounds<ScaledPixels>,
    /// The clip.
    pub content_mask: ContentMask<ScaledPixels>,
    /// Mesh space → scaled pixels.
    pub transformation: TransformationMatrix,
    /// What the vertex colours are multiplied by, for scaled pixels (see
    /// [`crate::Window::paint_mesh`]).
    pub background: Background,
    /// A gradient the vertex colours are multiplied by too, in mesh space (see
    /// [`crate::Window::paint_mesh_gradient`]).
    pub gradient: Option<Arc<MeshGradient>>,
    /// The geometry.
    pub mesh: Mesh,
}

impl MeshDraw {
    /// The part of the scene the draw may paint: its bounds within its clip.
    pub fn clipped_bounds(&self) -> Bounds<ScaledPixels> {
        self.bounds.intersect(&self.content_mask.bounds)
    }

    /// The draw's triangles as path vertices in scaled pixels, each with its paint: for
    /// renderers that rasterize meshes through their path pipeline instead of keeping them on
    /// the GPU. A solid paint is multiplied by the vertex colour exactly; a pattern or
    /// gradient takes the vertex alpha (meshes painted with one have white vertices). A mesh
    /// gradient is drawn in its average colour ([`MeshGradient::average_color`]).
    pub fn path_vertices(&self) -> impl Iterator<Item = (Point<ScaledPixels>, Background)> + '_ {
        let m = self.transformation;
        let solid = (self.background.tag == crate::BackgroundTag::Solid).then(|| {
            let paint = crate::Rgba::from(self.background.solid);
            match &self.gradient {
                Some(gradient) => {
                    let average = gradient.average_color();
                    crate::Rgba {
                        r: paint.r * average.r,
                        g: paint.g * average.g,
                        b: paint.b * average.b,
                        a: paint.a * average.a,
                    }
                }
                None => paint,
            }
        });
        self.mesh.vertices().iter().map(move |vertex| {
            let [x, y] = vertex.position;
            let position = point(
                ScaledPixels(
                    m.rotation_scale[0][0] * x + m.rotation_scale[0][1] * y + m.translation[0],
                ),
                ScaledPixels(
                    m.rotation_scale[1][0] * x + m.rotation_scale[1][1] * y + m.translation[1],
                ),
            );
            let color = vertex.color();
            let paint = match solid {
                Some(paint) => Background::from(Hsla::from(crate::Rgba {
                    r: paint.r * color.r,
                    g: paint.g * color.g,
                    b: paint.b * color.b,
                    a: paint.a * color.a,
                })),
                None => self.background.opacity(color.a),
            };
            (position, paint)
        })
    }
}

impl From<MeshDraw> for Primitive {
    fn from(mesh: MeshDraw) -> Self {
        Primitive::Mesh(mesh)
    }
}

/// A line made up of a series of vertices and control points.
#[derive(Clone, Debug)]
#[expect(missing_docs)]
pub struct Path<P: Clone + Debug + Default + PartialEq> {
    pub id: PathId,
    pub order: DrawOrder,
    pub bounds: Bounds<P>,
    pub content_mask: ContentMask<P>,
    pub vertices: Vec<PathVertex<P>>,
    pub color: Background,
    start: Point<P>,
    current: Point<P>,
    contour_count: usize,
}

impl Path<Pixels> {
    /// Create a new path with the given starting point.
    pub fn new(start: Point<Pixels>) -> Self {
        Self {
            id: PathId(0),
            order: DrawOrder::default(),
            vertices: Vec::new(),
            start,
            current: start,
            bounds: Bounds {
                origin: start,
                size: Default::default(),
            },
            content_mask: Default::default(),
            color: Default::default(),
            contour_count: 0,
        }
    }

    /// Scale this path by the given factor.
    pub fn scale(&self, factor: f32) -> Path<ScaledPixels> {
        Path {
            id: self.id,
            order: self.order,
            bounds: self.bounds.scale(factor),
            content_mask: self.content_mask.scale(factor),
            vertices: self
                .vertices
                .iter()
                .map(|vertex| vertex.scale(factor))
                .collect(),
            start: self.start.map(|start| start.scale(factor)),
            current: self.current.scale(factor),
            contour_count: self.contour_count,
            color: self.color,
        }
    }

    /// Move the start, current point to the given point.
    pub fn move_to(&mut self, to: Point<Pixels>) {
        self.contour_count += 1;
        self.start = to;
        self.current = to;
    }

    /// Draw a straight line from the current point to the given point.
    pub fn line_to(&mut self, to: Point<Pixels>) {
        self.contour_count += 1;
        if self.contour_count > 1 {
            self.push_triangle(
                (self.start, self.current, to),
                (point(0., 1.), point(0., 1.), point(0., 1.)),
            );
        }
        self.current = to;
    }

    /// Draw a curve from the current point to the given point, using the given control point.
    pub fn curve_to(&mut self, to: Point<Pixels>, ctrl: Point<Pixels>) {
        self.contour_count += 1;
        if self.contour_count > 1 {
            self.push_triangle(
                (self.start, self.current, to),
                (point(0., 1.), point(0., 1.), point(0., 1.)),
            );
        }

        self.push_triangle(
            (self.current, ctrl, to),
            (point(0., 0.), point(0.5, 0.), point(1., 1.)),
        );
        self.current = to;
    }

    /// Push a triangle to the Path.
    pub fn push_triangle(
        &mut self,
        xy: (Point<Pixels>, Point<Pixels>, Point<Pixels>),
        st: (Point<f32>, Point<f32>, Point<f32>),
    ) {
        self.bounds = self
            .bounds
            .union(&Bounds {
                origin: xy.0,
                size: Default::default(),
            })
            .union(&Bounds {
                origin: xy.1,
                size: Default::default(),
            })
            .union(&Bounds {
                origin: xy.2,
                size: Default::default(),
            });

        self.vertices.push(PathVertex {
            xy_position: xy.0,
            st_position: st.0,
            content_mask: Default::default(),
        });
        self.vertices.push(PathVertex {
            xy_position: xy.1,
            st_position: st.1,
            content_mask: Default::default(),
        });
        self.vertices.push(PathVertex {
            xy_position: xy.2,
            st_position: st.2,
            content_mask: Default::default(),
        });
    }
}

impl<T> Path<T>
where
    T: Clone + Debug + Default + PartialEq + PartialOrd + Add<T, Output = T> + Sub<Output = T>,
{
    #[allow(unused)]
    #[expect(missing_docs)]
    pub fn clipped_bounds(&self) -> Bounds<T> {
        self.bounds.intersect(&self.content_mask.bounds)
    }
}

impl From<Path<ScaledPixels>> for Primitive {
    fn from(path: Path<ScaledPixels>) -> Self {
        Primitive::Path(path)
    }
}

